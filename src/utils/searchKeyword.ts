/**
 * 정규표현식 기반의 스마트 키워드 정제 함수.
 * 사용자가 직접 추가한 커스텀 메뉴나 사전 매핑에 없는 메뉴명을 지도 검색용으로 깔끔하게 변환합니다.
 */
export function cleanSearchKeyword(rawName: string): string {
  if (!rawName) return '';

  let cleaned = rawName.trim();

  // 1. 괄호 내용 제거: (스시), [대만식], {추천} 등
  cleaned = cleaned.replace(/\([^)]*\)/g, '').replace(/\[[^\]]*\]/g, '');

  // 2. 특수문자 분리자(/, &, +, 와, 과)가 있을 경우, 첫 번째 주요 요소를 기준 삼거나 분리
  if (cleaned.includes('/')) {
    // 예: "차돌 / 우렁 된장찌개" -> 둘째 부분에 핵심 명사가 있으면 "우렁 된장찌개" -> "된장찌개"
    const parts = cleaned.split('/').map(p => p.trim()).filter(Boolean);
    // 가장 뒤쪽 토큰에 '찌개', '탕', '국밥', '덮밥', '구이', '볶음', '라면', '파스타' 등 핵심 명사가 있을 가능성이 높음
    const lastPart = parts[parts.length - 1];
    cleaned = lastPart.length >= 2 ? lastPart : parts[0];
  } else if (cleaned.includes('&')) {
    // 예: "짜장면 & 찹쌀탕수육" -> "짜장면" (앞의 대표 메뉴 채택)
    const parts = cleaned.split('&').map(p => p.trim()).filter(Boolean);
    cleaned = parts[0] || cleaned;
  } else if (cleaned.includes('+')) {
    const parts = cleaned.split('+').map(p => p.trim()).filter(Boolean);
    cleaned = parts[0] || cleaned;
  }

  // 3. 지도 검색을 방해하는 감성적/수식용 형용사 및 부사 제거
  const adjectivePattern = /^(바삭한|바삭|매콤한|매콤|얼큰한|얼큰|구수한|구수|진한|살얼음|노릇노릇한|노릇노릇|두툼한|두툼|시원한|뜨끈한|뜨끈|옛날|원조|겉바속촉|달콤한|달콤|새콤달콤한|새콤달콤|새콤|쫄깃한|쫄깃|직화|수비드|생명수|추억의|갓\s*구운|치즈\s*듬뿍|포르투갈식|대만식|태국식|베트남식)\s+/;
  cleaned = cleaned.replace(adjectivePattern, '');

  // 4. 후행 군더더기 제거 (세트, 정식, 플래터, 범벅 등)
  cleaned = cleaned.replace(/\s+(세트|정식|플래터|범벅|스타일)$/, '');

  cleaned = cleaned.trim();

  // 빈 문자열이 되면 원본 반환
  return cleaned || rawName;
}

/**
 * 메뉴 아이템에서 지도 검색에 가장 적합한 키워드를 도출합니다.
 * 1. MenuItem.searchKeyword 가 명시되어 있으면 우선 사용
 * 2. KNOWN_SEARCH_KEYWORDS 에 등록된 기본 메뉴 키워드 사용
 * 3. cleanSearchKeyword 스마트 정제 알고리즘 적용
 */
export function getSearchKeyword(menu: MenuItem): string {
  if (menu.searchKeyword && menu.searchKeyword.trim()) {
    return menu.searchKeyword.trim();
  }

  if (KNOWN_SEARCH_KEYWORDS[menu.name]) {
    return KNOWN_SEARCH_KEYWORDS[menu.name];
  }

  return cleanSearchKeyword(menu.name);
}
